declare(strict_types=1);

/**
 * Build a private, prefixed copy of wordpress/mcp-adapter and wordpress/php-mcp-schema at
 * vendor/vormbyte/mcp-adapter, so Vormbyte never shares classes, hooks, ability names or
 * user meta with the public MCP Adapter plugin or another plugin bundling it.
 *
 * - Namespaces WP\MCP and WP\McpSchema become Vormbyte\Vendor\WP\MCP and Vormbyte\Vendor\WP\McpSchema.
 * - Hook, filter and meta names mcp_adapter_* become vormbyte_mcp_adapter_*.
 * - Ability names mcp-adapter/..., the mcp-adapter category and WP-CLI command become vormbyte-mcp-adapter.
 *
 * Usage: php bin/scope-mcp-adapter.php <vendor-dir> [--delete-originals]
 */

$vendor = rtrim($argv[1] ?? (__DIR__ . '/../vendor'), '/\\');
$delete_originals = in_array('--delete-originals', $argv, true);

$sources = [
    'includes' => $vendor . '/wordpress/mcp-adapter/includes',
    'schema' => $vendor . '/wordpress/php-mcp-schema/src',
];
$target = $vendor . '/vormbyte/mcp-adapter';

foreach ($sources as $source) {
    if (!is_dir($source)) {
        fwrite(STDERR, "Missing source directory: {$source}\n");
        exit(1);
    }
}

function scope_remove_tree(string $dir): void
{
    if (!is_dir($dir)) {
        return;
    }
    $items = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST,
    );
    foreach ($items as $item) {
        $item->isDir() ? rmdir($item->getPathname()) : unlink($item->getPathname());
    }
    rmdir($dir);
}

function scope_php(string $code): string
{
    // Namespaces, imports and fully qualified names, including class names in strings that
    // escape the separator as a double backslash.
    $code = preg_replace(
        '/(?<![A-Za-z0-9_\\\\])(\\\\{0,2})WP(\\\\{1,2})(MCP|McpSchema)\b/',
        '$1Vormbyte$2Vendor$2WP$2$3',
        $code,
    );
    // Hook / filter / meta names.
    $code = preg_replace('/([\'"])mcp_adapter_/', '$1vormbyte_mcp_adapter_', (string) $code);
    // Ability names, category and WP-CLI command.
    $code = preg_replace('/([\'"])mcp-adapter([\'"\/])/', '$1vormbyte-mcp-adapter$2', (string) $code);

    return (string) $code;
}

scope_remove_tree($target);
$count = 0;
foreach ($sources as $name => $source) {
    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS));
    foreach ($files as $file) {
        $relative = substr($file->getPathname(), strlen($source) + 1);
        $destination = $target . '/' . $name . '/' . str_replace('\\', '/', $relative);
        if (!is_dir(dirname($destination))) {
            mkdir(dirname($destination), 0777, true);
        }
        $contents = (string) file_get_contents($file->getPathname());
        if ($file->getExtension() === 'php') {
            $contents = scope_php($contents);
            $count++;
        }
        file_put_contents($destination, $contents);
    }
}

$autoload = <<<'AUTOLOAD'
<?php

// Generated by bin/scope-mcp-adapter.php. Do not edit.

declare(strict_types=1);

spl_autoload_register(static function (string $class): void {
    static $prefixes = [
        'Vormbyte\\Vendor\\WP\\MCP\\' => __DIR__ . '/includes/',
        'Vormbyte\\Vendor\\WP\\McpSchema\\' => __DIR__ . '/schema/',
    ];
    foreach ($prefixes as $prefix => $dir) {
        if (strncmp($class, $prefix, strlen($prefix)) !== 0) {
            continue;
        }
        $file = $dir . str_replace('\\', '/', substr($class, strlen($prefix))) . '.php';
        if (is_file($file)) {
            require $file;
        }
        return;
    }
});

AUTOLOAD;
file_put_contents($target . '/autoload.php', $autoload);

foreach (['LICENSE.md' => 'wordpress/mcp-adapter', 'LICENSE-schema.md' => 'wordpress/php-mcp-schema'] as $dest => $pkg) {
    $license = $vendor . '/' . $pkg . '/LICENSE.md';
    if (is_file($license)) {
        copy($license, $target . '/' . $dest);
    }
}

if ($delete_originals) {
    scope_remove_tree($vendor . '/wordpress/mcp-adapter');
    scope_remove_tree($vendor . '/wordpress/php-mcp-schema');
}

echo "Scoped {$count} PHP files into {$target}\n";
